import jsPDF from 'jspdf';
import { format } from 'date-fns';

import { LOGO_BASE64 } from './logo';
import { LETTERHEAD_BASE64 } from './letterheadBase64';

export const generateRequestPDF = (request, userProfile) => {
    const doc = new jsPDF();

    // Brand Colors
    const primaryColor = [250, 204, 21]; // Yellow-400 equivalent
    const secondaryColor = [17, 24, 39]; // Gray-900 equivalent

    // --- Header ---
    doc.addImage(LOGO_BASE64, 'PNG', 160, 10, 30, 30);
    doc.setDrawColor(0, 0, 0);
    doc.setLineWidth(0.5);
    doc.line(20, 45, 190, 45);

    // --- Body ---
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(10);
    doc.setFont("helvetica", "normal");
    doc.text(`DATE: ${format(new Date(), 'MMMM d, yyyy')}`, 160, 60, { align: 'right' });

    // Recipient Info
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("To:", 20, 60);
    doc.setFont("helvetica", "normal");
    doc.text(request.name || "Staff Member", 20, 66);
    doc.text(request.email || userProfile?.email || "", 20, 72);
    if (userProfile?.staff_id) {
        doc.text(`Staff ID: ${userProfile.staff_id}`, 20, 78);
    }

    // Divider
    doc.setDrawColor(200, 200, 200);
    doc.line(20, 85, 190, 85);

    // Subject
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    const statusText = request.status === 'Approved' ? 'APPROVAL' : 'REJECTION';
    doc.text(`${request.type ? request.type.toUpperCase() : 'REQUEST'} ${statusText}`, 20, 100);

    // Content Logic
    doc.setFontSize(11);
    doc.setFont("helvetica", "normal");

    let contentY = 120;

    if (request.status === 'Approved') {
        const typeLabel = request.type === 'Leave' ? `${request.leave_type} Leave` : request.type;

        doc.text(`Dear ${(request.name || 'Member').split(' ')[0]},`, 20, contentY);
        contentY += 10;

        doc.text(`We are pleased to inform you that your request for ${typeLabel} has been APPROVED.`, 20, contentY);
        contentY += 10;

        if (request.type === 'Leave' && request.dates) {
            doc.text(`Authorized Dates: ${request.dates.length} days`, 20, contentY);
            contentY += 6;
            const dateRange = `${format(new Date(request.dates[0]), 'MMM d, yyyy')} - ${format(new Date(request.dates[request.dates.length - 1]), 'MMM d, yyyy')}`;
            doc.text(`(${dateRange})`, 20, contentY);
            contentY += 10;
        } else if (request.amount) {
            doc.text(`Authorized Amount: KES ${request.amount.toLocaleString()}`, 20, contentY);
            contentY += 10;
        }

        doc.text("Please retain this document for your records.", 20, contentY + 10);

    } else {
        doc.text(`Dear ${request.name?.split(' ')[0] || 'Member'},`, 20, contentY);
        contentY += 10;

        doc.text(`We regret to inform you that your request has been DECLINED at this time.`, 20, contentY);
        contentY += 10;

        doc.text("If you have any questions, please contact the HR administration.", 20, contentY + 10);
    }

    // --- Footer ---
    const footerY = 250;
    doc.setDrawColor(200, 200, 200);
    doc.line(20, footerY, 190, footerY);

    doc.setFontSize(8);
    doc.setTextColor(100, 100, 100);
    doc.text("This document was automatically generated by the POT OF JOLLOF LTD System.", 105, footerY + 10, { align: 'center' });
    doc.text(`Reference ID: ${request.id}`, 105, footerY + 15, { align: 'center' });

    // Save or Return
    if (userProfile?.returnBase64) {
        return doc.output('datauristring').split(',')[1]; // Return raw base64
    } else {
        doc.save(`${request.type || 'Request'}_${request.status || 'Update'}_${format(new Date(), 'yyyyMMdd')}.pdf`);
    }
};

export const generateReceiptPDF = (data) => {
    const doc = new jsPDF();

    // Brand Colors
    const primaryColor = [250, 204, 21];
    const secondaryColor = [17, 24, 39];

    // --- Header (Ink Saving: No solid rectangle) ---

    // Logo (Added)
    doc.addImage(LOGO_BASE64, 'PNG', 185, 2, 16, 16);

    doc.setTextColor(0, 0, 0);
    doc.setFontSize(18);
    doc.setFont("helvetica", "bold");
    doc.text("POT OF JOLLOF LTD", 20, 13);

    // --- Meta Data ---
    doc.setTextColor(0, 0, 0);
    doc.setFontSize(10);

    // Right side: Date and Receipt #
    doc.text(`DATE: ${format(new Date(data.date), 'MMMM d, yyyy')}`, 190, 60, { align: 'right' });
    if (data.reference) {
        doc.text(`REF: ${data.reference}`, 190, 66, { align: 'right' });
    }

    // Left side: Supplier Info
    doc.setFontSize(12);
    doc.setFont("helvetica", "bold");
    doc.text("Received From:", 20, 60);
    doc.setFont("helvetica", "normal");
    doc.text(data.supplier, 20, 66);
    doc.text(`Payment Method: ${data.paymentMethod}`, 20, 72);

    // --- Table ---
    // We need autoTable for the list
    import('jspdf-autotable').then(({ default: autoTable }) => {
        autoTable(doc, {
            startY: 85,
            head: [['Description', 'Qty', 'Unit Price', 'Total']],
            body: data.items.map(item => [
                item.description,
                item.quantity,
                `KES ${item.price.toLocaleString()}`,
                `KES ${(item.quantity * item.price).toLocaleString()}`
            ]),
            foot: [['', '', 'Grand Total', `KES ${data.total.toLocaleString()}`]],
            theme: 'striped',
            headStyles: { fillColor: secondaryColor, textColor: [255, 255, 255] },
            footStyles: { fillColor: [240, 240, 240], textColor: [0, 0, 0], fontStyle: 'bold' },
            styles: { fontSize: 10, cellPadding: 3 },
            columnStyles: {
                0: { cellWidth: 'auto' }, // Description
                1: { cellWidth: 20 },     // Qty
                2: { cellWidth: 40 },     // Price
                3: { cellWidth: 40, halign: 'right' } // Total
            }
        });

        // --- Footer ---
        const finalY = doc.lastAutoTable.finalY + 30;

        doc.setDrawColor(200, 200, 200);
        doc.line(20, finalY, 190, finalY);

        doc.setFontSize(8);
        doc.setTextColor(100, 100, 100);
        doc.text("This document was automatically generated by the POT OF JOLLOF LTD System.", 105, finalY + 10, { align: 'center' });
        doc.text(`Generated on ${format(new Date(), 'PPpp')}`, 105, finalY + 15, { align: 'center' });

        doc.save(`Receipt_${data.supplier.replace(/\s+/g, '_')}_${data.date}.pdf`);
    });
};


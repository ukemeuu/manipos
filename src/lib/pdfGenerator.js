    doc.text(`Dear ${docData.staffName ? docData.staffName.split(' ')[0] : 'Member'},`, 20, y);
    y += 10;
    
    // Split content text
    const textLines = doc.splitTextToSize(docData.content?.text || '', 170);
    doc.text(textLines, 20, y);
    
    y += (textLines.length * 5) + 30;

    doc.text("Issued By:", 20, y);
    doc.text("POT OF JOLLOF LTD Management", 20, y + 6);
    
